import {test,expect} from "@playwright/test";
import {initialCurry,successorsCurry} from "../../experiments/curry-power.js";
test("curry playtest is separate from normal game, fits iPhone and allows local turns",async({page},info)=>{
 const errors=[];page.on("pageerror",e=>errors.push(String(e)));
 await page.goto("/experiments/curry-play.html");
 await expect(page.locator("#board .cell")).toHaveCount(49);
 await expect(page.locator(".curry")).toHaveCount(2);
 await expect(page.locator("#status")).toContainText("壁を選ぼう");
 const rect=await page.locator("#board").boundingBox();
 expect(Math.abs(rect.width-rect.height)).toBeLessThan(2);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator("#mode").selectOption("local");
 await page.locator("#new").click();
 let state=initialCurry(2);
 const a=successorsCurry(state).find(x=>x.a.wall===null);
 expect(a).toBeDefined();
 await page.locator("#skip").click();
 await page.locator("#directions button").nth(a.a.dir).click();
 await expect(page.locator("#status")).toContainText("壁を選ぼう");
 await expect(page.locator("#last")).toContainText("プレイヤー1");
 await page.locator("#undo").click();
 await expect(page.locator("#last")).toBeEmpty();
 await page.locator("#skip").click();
 await page.locator("#undo").click();
 await expect(page.locator("#status")).toContainText("壁を選ぼう");
 await page.screenshot({path:info.outputPath("curry-playtest.png"),fullPage:true});
 expect(errors).toEqual([]);
});
test("curry experimental CPU responds without blocking and resets",async({page})=>{
 const errors=[];page.on("pageerror",e=>errors.push(String(e)));
 await page.goto("/experiments/curry-play.html");
 await page.locator("#skip").click();
 await page.locator("#directions button:not([disabled])").first().click();
 await expect(page.locator("#last")).toContainText("プレイヤー2",{timeout:30000});
 await expect(page.locator("#skip")).toBeEnabled({timeout:30000});
 await page.locator("#new").click();
 await expect(page.locator("#last")).toBeEmpty();
 await expect(page.locator(".curry")).toHaveCount(2);
 expect(errors).toEqual([]);
});


test("a human can collect curry and move one wall THREE cells on the next own turn",async({page})=>{
 await page.goto("/experiments/curry-play.html");
 await page.locator("#mode").selectOption("local");
 // Historical route is specific to the old comparison placement.
 await page.locator("#curryPair").selectOption("13,35");
 await page.locator("#new").click();
 const move=async(wallFrom,wallTo,dir)=>{
   if(wallFrom===null)await page.locator("#skip").click();
   else {await page.locator('[data-cell="'+wallFrom+'"]').click();
     await page.locator('[data-cell="'+wallTo+'"]').click();}
   await page.locator("#directions button").nth(dir).click();
 };
 // Exact legal 5-ply path, generated by the isolated rules engine.
 await move(null,null,0);
 await move(36,43,2);
 await move(43,42,2); // P1 stops on curry at cell 35.
 await expect(page.locator(".curry")).toHaveCount(1);
 await expect(page.locator("#scores")).toContainText("🍛 次の自分の番");
 await move(null,null,0);
 await expect(page.locator("#status")).toContainText("最大3マス");
 await page.locator('[data-cell="22"]').click();
 await expect(page.locator('[data-cell="43"]')).toContainText("3");
 await page.locator('[data-cell="43"]').click();
 await page.locator("#directions button").nth(0).click();
 await expect(page.locator("#last")).toContainText("パワー使用！");
 await expect(page.locator("#scores")).not.toContainText("🍛 次の自分の番");
 await expect(page.locator(".curry")).toHaveCount(1);
});


