import fs from 'node:fs';
import {generate,MODES,FAMILIES} from './board-generator.js';
import {newGame,advanceGame,verifyGame} from './tactics-completion.js';
const out='reports/five-board';fs.mkdirSync(out,{recursive:true});
const proposals=[],rejected=[];
for(const [id,size] of MODES)for(const family of FAMILIES)for(const target of [3,4])for(const density of [.12,.20])for(let k=0;k<2;k++){
 const spec={id,size,stars:2*target-1,target,walls:Math.round(size*size*density),family,seed:1000+proposals.length+rejected.length};
 try{proposals.push(generate(spec));}catch(e){rejected.push({spec,reason:e.message});}
}
fs.writeFileSync(out+'/proposals.json',JSON.stringify({proposals,rejected}));
const archive=fs.openSync(out+'/games.jsonl','w');const rows=[];
function play(candidate,stage,policies,seed){for(const starter of [0,1]){
 let g=newGame(candidate.state,{starter,policies,seed,id:`${candidate.id}-${candidate.seed}-${stage}-${policies.join('-')}-${seed}-${starter}`});
 for(const maxPlies of [256,1024]){g=advanceGame(g,{maxPlies,timeBudgetMs:stage==='screen'?120:400,memoryBudgetMb:512});if(g.reason==='win')break;}
 verifyGame(g);fs.writeSync(archive,JSON.stringify(g)+'\n');rows.push({id:candidate.id,candidate:candidate.seed,stage,policies,seed,starter,winner:g.state.winner,reason:g.reason,plies:g.state.ply,repetition:g.repetitionCount,metrics:g.metrics});
}}
const selected=[];
for(const [id] of MODES){
 const pool=proposals.filter(c=>c.id===id).sort((a,b)=>a.diagnostics.distanceGap-b.diagnostics.distanceGap);
 const shortlist=FAMILIES.map(f=>pool.find(c=>c.family===f)).filter(Boolean);
 for(const c of shortlist)play(c,'screen',['positional','positional'],11);
 const rank=c=>{const r=rows.filter(x=>x.candidate===c.seed);return r.filter(x=>x.winner===null).length*10+Math.abs(r.filter(x=>x.winner===x.starter).length-1)+c.diagnostics.distanceGap/100;};
 shortlist.sort((a,b)=>rank(a)-rank(b));const best=shortlist[0];selected.push(best);
 for(const seed of [101,102,103,104])for(const pair of [['search','search'],['mixed','mixed'],['star','defensive'],['defensive','star']])play(best,'precision',pair,seed);
 for(const seed of [9001,9002,9003,9004])for(const pair of [['search-progress','search-progress'],['search','mixed'],['mixed','search']])play(best,'holdout',pair,seed);
 console.log(id,'complete',rows.filter(r=>r.id===id).length);
}
fs.closeSync(archive);fs.writeFileSync(out+'/selected.json',JSON.stringify(selected,null,2));fs.writeFileSync(out+'/rows.json',JSON.stringify(rows));
fs.writeFileSync('src/research-layouts.js','// Generated by scripts/five-board-study.js. All unapproved research fixtures.\nexport const RESEARCH_LAYOUTS='+JSON.stringify(selected.map(c=>({...c.state,id:c.id,seed:c.seed,family:c.family,name:`【検証用】${c.id} ${c.state.size}×${c.state.size}`})),null,2)+';\n');
